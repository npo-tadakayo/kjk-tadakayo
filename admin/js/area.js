function normalize(s) {
  return String(s ?? "")
    .replace(/[Ａ-Ｚａ-ｚ０-９]/g, (c) => String.fromCharCode(c.charCodeAt(0) - 0xfee0))
    .replace(/[\s　]+/g, " ")
    .trim();
}

/**
 * 住所文字列から { prefecture, region, city } を返す。
 * 取れなかった項目は "" を返す（呼び出し側で「—」や「未登録」に落とす）。
 */
export function parseAddress(address) {
  const a = normalize(address);
  if (!a) return { prefecture: "", region: "", city: "" };

  // 郵便番号や「〒」が頭にあっても拾えるよう、都道府県名を先頭から探さず最初の出現で取る
  const pref = PREFECTURES.find((p) => a.includes(p)) || "";

  // 都道府県が書かれていない住所は、先頭の市名から逆引きする
  if (!pref) {
    const m0 = a.match(CITY_RE);
    const city0 = m0 ? m0[1] : "";
    const guessed = PREF_OF_CITY[city0] || "";
    if (!guessed) return { prefecture: "", region: "", city: "" };
    return { prefecture: guessed, region: REGION_OF[guessed] || "", city: city0 };
  }

  const rest = a.slice(a.indexOf(pref) + pref.length);
  let city = "";
  const m = rest.match(CITY_RE);
  if (m) {
    city = m[1];
    // 「◯◯郡△△町」→「△△町」
    const gun = city.match(/郡(.+[町村])$/);
    if (gun) city = gun[1];
  }
  return { prefecture: pref, region: REGION_OF[pref] || "", city };
}

/**
 * 案件（case）と事業所辞書から住所情報を得る。
 * offices に prefecture / city が入るようになったら、ここが先に効く。
 */
export function areaOf(caseObj, officesById) {
  const office = officesById?.[caseObj?.officeId] || null;
  if (office && (office.prefecture || office.city)) {
    const pref = office.prefecture || "";
    return { prefecture: pref, region: REGION_OF[pref] || "", city: office.city || "" };
  }
  return parseAddress(office?.address || caseObj?.address || "");
}
