// 依頼ドキュメントに焼き込まれた条文を安全に読む（欠けは現行版で補わない＝
// 署名対象の文面を勝手に差し替えないため、壊れていたら null を返して呼び出し側で止める）
export function parseEmbeddedDocument(raw) {
  if (!raw || typeof raw !== "object") return null;
  const sections = Array.isArray(raw.sections)
    ? raw.sections
        .map((s) => ({
          key: String(s?.key ?? "").trim(),
          title: String(s?.title ?? "").trim(),
          body: String(s?.body ?? "").trim(),
        }))
        .filter((s) => s.title && s.body)
    : [];
  if (!sections.length) return null;
  const version = String(raw.version ?? "").trim();
  const title = String(raw.title ?? "").trim();
  const consent = String(raw.consent_statement ?? "").trim();
  if (!version || !title || !consent) return null;
  return {
    version,
    title,
    preamble: String(raw.preamble ?? "").trim(),
    sections,
    terms_url: String(raw.terms_url ?? "").trim(),
    // 1.1 で足したもの。1.0 で発行済みの依頼には入っていないので空文字になる
    privacy_url: String(raw.privacy_url ?? "").trim(),
    consent_statement: consent,
    issuer: String(raw.issuer ?? "").trim(),
    issuer_detail: String(raw.issuer_detail ?? "").trim(),
  };
}
